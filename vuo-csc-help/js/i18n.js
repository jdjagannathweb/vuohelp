let currentLanguage = localStorage.getItem('vuo_lang') || 'en';

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'or') lang = 'en';
  currentLanguage = lang;
  localStorage.setItem('vuo_lang', lang);
  applyTranslations();
  
  // Dispatch language change event for dynamic components
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function getTranslation(key) {
  const dict = VUO_I18N[currentLanguage] || VUO_I18N.en;
  return dict[key] || VUO_I18N.en[key] || key;
}

function applyTranslations() {
  const dict = VUO_I18N[currentLanguage] || VUO_I18N.en;
  
  // Translate text nodes with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update Language toggle button visual state
  const langEnBtn = document.getElementById('langToggleEn');
  const langOrBtn = document.getElementById('langToggleOr');
  if (langEnBtn && langOrBtn) {
    if (currentLanguage === 'en') {
      langEnBtn.className = 'px-2.5 py-1 text-xs font-bold rounded bg-sky-500 text-white shadow-sm';
      langOrBtn.className = 'px-2.5 py-1 text-xs font-semibold rounded text-slate-300 hover:text-white';
    } else {
      langOrBtn.className = 'px-2.5 py-1 text-xs font-bold rounded bg-sky-500 text-white shadow-sm font-odia';
      langEnBtn.className = 'px-2.5 py-1 text-xs font-semibold rounded text-slate-300 hover:text-white';
    }
  }
}
